    set_cell(tbl.rows[0].cells[1], number, align=WD_ALIGN_PARAGRAPH.RIGHT, size=14)
    tbl.rows[0].cells[0].width = Cm(13)
    tbl.rows[0].cells[1].width = Cm(2)
    empty_line(doc)


